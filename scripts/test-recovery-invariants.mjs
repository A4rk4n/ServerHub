import assert from "node:assert/strict";
import fs from "node:fs";
const runtime = fs.readFileSync("src/lib/runtime.ts", "utf8");
const games = fs.readFileSync("src/lib/games.ts", "utf8");
const proxy = fs.readFileSync("src/proxy.ts", "utf8");
const launcher = fs.readFileSync("scripts/portable-launcher.cjs", "utf8");
for (const marker of ["yauzl", "isSymlink", "maxEntries", "maxExpandedBytes", "validateEntrySizes", "redactLogSecrets"]) assert.ok(runtime.includes(marker), marker);
assert.ok(!runtime.includes('from "adm-zip"'));
for (const marker of ["dragonwilds", "hytale"]) assert.ok(games.includes(marker), marker);
for (const marker of ["SERVERHUB_STEAMCMD_PATH", "SERVERHUB_HYTALE_DOWNLOADER_PATH", "Java 25", "HytaleServer.jar", "Assets.zip"]) assert.ok(runtime.includes(marker), marker);
for (const marker of ["localhost", "127.0.0.1", "::1", "origin.port === host.port"]) assert.ok(proxy.includes(marker), marker);
assert.ok(launcher.includes('@webviewjs/webview'));
assert.ok(!/(explorer\.exe|--app=|msedge|chrome\.exe)/i.test(launcher));
assert.ok(launcher.includes('serverhub:shutdown'));
